#!/usr/bin/env node
// Bakes the Alien scene's loops to video: renders every frame of every loop
// on the bake page (src/render/scenes/alien/bakePage.ts, served by the dev
// server at /tools/alien-bake/), saves them as PNGs, and encodes each loop
// with ffmpeg (H.264, which every browser and TV the app targets decodes) into
// public/media/alien/ under the next free loop<i>-v<n>.mp4 name: a committed
// video is never overwritten, since a tab loaded before a deploy may still
// fetch it (src/pinnedAssets.ts's header, "Scene media"). Then it rewrites
// src/render/scenes/alien/loops/manifest.ts, which the scene reads: the frame
// rate, the frame size, and per loop its clip, file, frame count, length and
// Bounce pivot; a loop left out with --loops keeps its file. Add each new
// video to tests/mediaManifest.ts (tests/sceneMedia.test.ts prints the line).
//
//   npm run dev -- --port 5321
//   node tools/alien-bake.mjs --port 5321 [--fps 120] [--size 1280x720] [--crf 22] [--loops 0,2]
//
// --fps is frames per second of dance at 1× speed. More than the screen's
// rate is the point: when Move plays a loop slower, each screen refresh still
// gets a new frame (half speed at 120 is 60 frames a second), with no blending
// between frames, which would double the wire's thin lines. ffmpeg comes from
// $FFMPEG, else the PATH. Rerun after changing the alien, a loop's clip or
// camera, or the look; tests/alien.test.ts checks the manifest still matches
// LOOPS.
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { BAKED as PREVIOUS } from "../src/render/scenes/alien/loops/manifest.ts";

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const port = opt("port", "5173");
const fps = Number(opt("fps", "120"));
const [width, height] = opt("size", "1280x720").split("x").map(Number);
// 22 keeps the face's fine mesh; 26 smeared it (2026-10-05, the scene record).
const crf = opt("crf", "22");
const only = opt("loops", null)?.split(",").map(Number) ?? null;
const ffmpeg = process.env.FFMPEG || "ffmpeg";
const outDir = path.resolve("public/media/alien");
const manifestPath = path.resolve("src/render/scenes/alien/loops/manifest.ts");
mkdirSync(outDir, { recursive: true });

/** The next free name for loop `i`: one past the highest `loop<i>-v<n>.mp4` here. */
function nextFile(i) {
  const re = new RegExp(`^loop${i}-v(\\d+)\\.mp4$`);
  const taken = readdirSync(outDir).map((f) => Number(re.exec(f)?.[1] ?? 0));
  return `loop${i}-v${1 + Math.max(0, ...taken)}.mp4`;
}

const browser = await chromium.launch({
  channel: "chromium",
  args: ["--enable-gpu", "--use-angle=metal", "--enable-gpu-rasterization", "--ignore-gpu-blocklist"],
});
const page = await (await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width, height } })).newPage();
page.on("pageerror", (e) => console.error("bake page:", e.message));
await page.goto(`https://localhost:${port}/tools/alien-bake/index.html?w=${width}&h=${height}`);
const info = await page.evaluate(() => window.__bake.ready);

const manifest = { fps, width, height, loops: [] };
for (const [i, loop] of info.loops.entries()) {
  const frames = Math.round(loop.seconds * fps);
  const rebake = !only || only.includes(i);
  const file = rebake ? nextFile(i) : path.basename(PREVIOUS.loops[i].file);
  manifest.loops.push({ clip: loop.clip, file: `/media/alien/${file}`, frames, seconds: frames / fps, pivot: loop.pivot.map((v) => +v.toFixed(4)) });
  if (!rebake) continue;
  const dir = mkdtempSync(path.join(tmpdir(), `alien-bake-${i}-`));
  const t0 = Date.now();
  for (let f = 0; f < frames; f++) {
    const url = await page.evaluate(([l, p]) => window.__bake.frame(l, p), [i, f / frames]);
    writeFileSync(path.join(dir, `${String(f).padStart(5, "0")}.png`), Buffer.from(url.split(",")[1], "base64"));
  }
  execFileSync(ffmpeg, [
    "-v", "error", "-y", "-framerate", String(fps), "-i", path.join(dir, "%05d.png"),
    "-c:v", "libx264", "-preset", "slow", "-crf", crf, "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an",
    path.join(outDir, file),
  ]);
  rmSync(dir, { recursive: true, force: true });
  const kb = Math.round(statSync(path.join(outDir, file)).size / 1024);
  console.log(`loop ${i} (${loop.clip}): ${frames} frames in ${((Date.now() - t0) / 1000).toFixed(0)} s -> ${file}, ${kb} KB`);
}
const manifestTs =
  "// Generated by tools/alien-bake.mjs — rerun it rather than editing this file.\n" +
  "// What the baked loop videos in public/media/alien/ hold; older builds play them, the scene draws live.\n" +
  `export const BAKED = ${JSON.stringify(manifest, null, 2)} as const;\n`;
writeFileSync(manifestPath, manifestTs);
console.log("manifest:", manifestPath);
console.log("Add each new video to tests/mediaManifest.ts: tests/sceneMedia.test.ts prints the lines.");
await browser.close();
